          <h4>الشروط الأخرى:</h4>
          <p>1.	من خلال المشاركة في هذا اللحملة الترويجية، يوافق الزبون على سياسة الخصوصية الخاصة بـ بيرت (هنكل). تتحمل بيرت (هنكل) مسؤولية جمع ومعالجة واستخدام البيانات الشخصية للمشاركين. سيتم استخدام البيانات الشخصية فقط ضمن إطار أحكام قانون حماية البيانات. ستقوم بيرت (هنكل) بتخزين ومعالجة واستخدام المعلومات فقط بقدر ما هو ضروري لتنفيذ المسابقة، أو إذا أعطى الزبون موافقته. يشمل ذلك استخدام البيانات لممارسة الحقوق الممنوحة. سيتم حذف البيانات الشخصية للزبائن بعد انتهاء الحملة. يمكن للزبائن طلب معلومات حول البيانات المخزنة عنهم في أي وقت. في حالة الفوز، يوافق الفائز على نشر اسمه ومدينة إقامته في وسائل الإعلان المستخدمة من قبل بيرت (هنكل)، بما في ذلك الإعلان عن الفائز على الموقع الإلكتروني والقنوات الاجتماعية.</p>
          <p>2.	يعتبر الاشتراك في الحملة الترويجية بمثابة موافقة من الزبون للشركة والشركات التابعة لها باستخدام اسمه ومعلوماته الشخصية وأي تصريحات يقدمها فيما يتعلق بالحملة لأغراض إعلانية فقط، دون إشعار إضافي أو تعويض إضافي، إلا إذا كان ذلك محظورًا بموجب القانون. سيتم التعامل مع جميع المعلومات وفقًا لقوانين حماية البيانات ذات الصلة وسياسة الخصوصية الخاصة بالشركة.</p>
          <p>3.	لا تتحمل الشركة أي مسؤولية عن أي خسارة أو ضرر أو إصابة أو أرباح مفقودة أو أضرار مباشرة أو غير مباشرة أو تبعية أو عرضية أو تعويضية قد تحدث نتيجة المشاركة في العرض الترويجي، أو امتلاك أو قبول أو استخدام أو إساءة استخدام الجائزة.</p>
