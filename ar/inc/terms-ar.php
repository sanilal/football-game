          <h3>’اربح مع بيرت‘ (“الحملة الترويجية”)</h3>
         <p>الحملة الترويجية “اربح مع بيرت” (“الحملة”) ساري المفعول من 23 يناير حتى 22 فبراير 2025 في جميع أنحاء المملكة العربية السعودية.</p>
         <p>الحملة الترويجية متاحة لجميع سكان المملكة العربية السعودية الذين تبلغ أعمارهم 18 عامًا أو أكثر، ولديهم هوية وطنية سارية أو جواز سفر ساري، باستثناء المروجين داخل المتاجر، وجميع الشركات التابعة لشركة بيرت (هنكل) وأي أفراد أو مجموعات أخرى مشاركة في هذا الحملة الترويجية.</p>
        <h4>شروط المشاركة وآلية الحملة الترويجية:</h4>
        <p>1.	يمكن للمشاركين دخول المسابقة مع أو بدون شراء المنتجات الترويجية.</p>
        <p>2.	للمشاركة في الحملة، يجب على الزبون مسح رمز الاستجابة السريعة، زيارة الموقع الإلكتروني www.winwithpert.com، وملء النموذج بالاسم ومعلومات الاتصال من 23 يناير 2025 الساعة 00:01 صباحًا وحتى 22 فبراير 2025 الساعة 11:59 مساءً.</p>
        <p>3.	يمكن للمشاركين زيادة فرصهم في الفوز فقط عن طريق إدخال إثبات شراء صالح.</p>
        <p>4.	لزيادة فرصهم، يجب على الزبون شراء أي منتج من منتجات بيرت من المتاجر المشاركة وزيارة الموقع الإلكتروني www.winwithpert.com من 23 يناير 2025 (من الساعة 00:01 صباحًا) وحتى 22 فبراير 2025 (حتى الساعة 11:59 مساءً).</p>
        <p>5.	المنتجات المشتراة فقط بين 23 يناير و22 فبراير 2025 (بما في ذلك كلا التاريخين) ستكون مؤهلة.</p>
        <p>6.	يجب على الزبون اتباع التعليمات الخاصة بالعرض من خلال ملء نموذج التسجيل عبر الإنترنت بالكامل ببياناته الشخصية الصحيحة: الاسم الكامل، عنوان البريد الإلكتروني، ورقم الهاتف.</p>
        <p>7.	يجب على الزبون تحميل صورة واحدة على الأقل من الإيصال المطبوع الصالح بالكامل، مع اظهار اسم المنتج (المنتجات) المشترى، رقم الإيصال/الفاتورة، وتاريخ الشراء بشكل واضح ومقروء.</p>
        <p>8.	يُستثنى موظفو بيرت (هنكل)، والشركات التابعة وأفراد أسرهم المباشرين (الآباء، الأجداد، الأبناء، الأحفاد، الأشقاء، الأقارب بالنسب – الأم، الأب، الأخ، الأخت، الابنة، والابن – والأزواج) من الحملة الترويجية. أي مشاركة من هؤلاء الأشخاص في الحملة بما يخالف هذا الشرط سيتم اعتبارها باطلة تلقائيًا.</p>
        <p>9.	في أي مرحلة من مراحل الحملة الترويجية، إذا تم اكتشاف استخدام أساليب غير قانونية أو غش من قبل زبون مشارك، فسيؤدي ذلك إلى استبعاده وحظره من المشاركة المستقبلية في العرض. يُمنع استخدام أي برامج آلية أو أي وسيلة ميكانيكية أو إلكترونية أخرى تتيح للعميل دخول المسابقة تلقائيًا.</p>


