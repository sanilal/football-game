          <p>5.	تخضع الحملة الترويجية وهذه الشروط والأحكام للقوانين والأنظمة المعمول بها في المملكة العربية السعودية. تكون قرارات الشركة فيما يتعلق بجميع الأمور المتعلقة بالحملة الترويجية نهائية وغير قابلة للاستئناف.</p>
          <p>6.	تحتفظ الشركة بالحق في تعديل أو إلغاء أو سحب أي من شروط الحملة، بما في ذلك الحق في استبدال أي جائزة بأخرى ذات قيمة مساوية، بعد الحصول على موافقة .COC </p>
